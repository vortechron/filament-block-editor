/** Also accepts "MapPin", "mapPin" and "map_pin". */
export function iconByName(name: string | null | undefined): LucideIcon {
    if (!name) {
        return Blocks;
    }

    const plain = name.trim().replace(/^lucide-/, '');
    const key = plain
        .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
        .replace(/([A-Za-z])(\d)/g, '$1-$2')
        .replace(/[_\s]+/g, '-')
        .toLowerCase();

    return ICONS[plain.toLowerCase()] ?? ICONS[key] ?? Blocks;
}
